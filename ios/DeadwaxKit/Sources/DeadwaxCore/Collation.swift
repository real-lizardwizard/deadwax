    /// Those weighing as the one before them at the first level, and after it at the second.
    static let scriptTies: Set<UInt32> = [0x0491]
    /// The letters ICU weighs as their own though they decompose to another and a mark (й): the
    /// two, then the letter.
    static let contractions: [UInt32] = [
        0x0418, 0x0306, 0x0419, 0x0438, 0x0306, 0x0439, 0x0627, 0x0653, 0x0622, 0x0627, 0x0654, 0x0623,

    /// Where ICU's symbols begin among `variables`, and its currency.
    static let firstSymbol: UInt32 = 0x0060
    static let firstCurrency: UInt32 = 0x00A4

    // the first level's bands, in ICU's order: in each, the characters a table lists by their rank there, then any other
    // by code point - but for the symbols, whose last listed ones (CJK's, the modifier letters ICU weighs as symbols)
    // stand after every other
    static let punctuationBand: UInt32 = 0x0100_0000
    static let symbolBand: UInt32 = 0x0200_0000
    static let lastSymbolsBand: UInt32 = 0x0280_0000
    static let currencyBand: UInt32 = 0x0300_0000
    static let digitBand: UInt32 = 0x0400_0000
    static let latinBand: UInt32 = 0x0500_0000
    static let scriptBand: UInt32 = 0x0600_0000
    static let hangulBand: UInt32 = 0x0700_0000
    static let kanaBand: UInt32 = 0x0800_0000
    static let bopomofoBand: UInt32 = 0x0900_0000
    static let yiBand: UInt32 = 0x0A00_0000
    static let hanBand: UInt32 = 0x0B00_0000
    static let unlisted: UInt32 = 0x10_0000

    // the second level: a letter's own; above it, the tables' marks, then any other mark, then an expansion's own, then
    // a tie's steps
    static let base: UInt32 = 0x20
    static let unlistedMark: UInt32 = 0x1000
    static let expansionMark: UInt32 = 0x4000
    static let tieStep: UInt32 = 0x8000

    // the third level: ICU's tertiary weights - lowercase, a compatibility form of one, an expansion (æ, ß), uppercase,
    // a compatibility form of one, an expansion of one; small hiragana, hiragana, small katakana, katakana; the numbers
    // ICU weighs as digits (15 to 19, `numbers`' own); a superscript, an ordinal, a circled number or a halfwidth kana
    static let lower: UInt32 = 0x02, compatLower: UInt32 = 0x03, expanded: UInt32 = 0x04
    static let upper: UInt32 = 0x08, compatUpper: UInt32 = 0x09, expandedUpper: UInt32 = 0x0A
    static let smallHiragana: UInt32 = 0x0B, hiragana: UInt32 = 0x0C, smallKatakana: UInt32 = 0x0D, katakana: UInt32 = 0x0E
    static let special: UInt32 = 0x14

    struct Element: Equatable {
        let primary, secondary, tertiary: UInt32
    }

    struct Weight {
        let primary, secondary: UInt32
    }

    struct Number {
        let value, tertiary: UInt32
    }

    /// `variables` weighed: a rank in its band at the first level each, a step at the second for a tie.
    static let variableWeights: [UInt32: Weight] = {
        var weights: [UInt32: Weight] = [:]
        var band = punctuationBand, rank: UInt32 = 0, step: UInt32 = 0
        for scalar in variables {
            if scalar == firstSymbol { band = symbolBand }
            if scalar == unlistedSymbolsBefore { band = lastSymbolsBand }
            if scalar == firstCurrency { band = currencyBand }
            if variableTies.contains(scalar) { step += 1 } else { rank += 1; step = 0 }
            weights[scalar] = Weight(primary: band + rank, secondary: base + step * tieStep)
        }
        return weights
    }()

    static let space: UInt32 = variableWeights[0x20]?.primary ?? punctuationBand

    /// `marks` weighed at the second level: 8 for each before it, and 8 more - as the tables' `variants` count.
    static let markWeights: [UInt32: UInt32] = {
        var weights: [UInt32: UInt32] = [:]
        var rank: UInt32 = 0
        for scalar in marks {
            if !markTies.contains(scalar) { rank += 1 }
            weights[scalar] = base + 8 * rank
        }
        return weights
    }()

    /// `letterPlaces` and `scriptLetters` weighed: each's place in its band at the first level, a step at the second for
    /// a tie - and one sharing the place before it without one, the same.
    static let letterWeights = placed(letterPlaces, letterTies, latinBand)
    static let scriptWeights = placed(scriptLetters, scriptTies, scriptBand)

    static func placed(_ pairs: [UInt32], _ ties: Set<UInt32>, _ band: UInt32) -> [UInt32: Weight] {
        var weights: [UInt32: Weight] = [:]
        var last: UInt32 = 0, step: UInt32 = 0
        for index in stride(from: 0, to: pairs.count - 1, by: 2) {
            let scalar = pairs[index], place = pairs[index + 1]
            if ties.contains(scalar) { step += 1 } else if place != last { step = 0 }
            last = place
            weights[scalar] = Weight(primary: band + place, secondary: base + step * tieStep)
        }
        return weights
    }

    /// `markLetters`, each by its scalar.
    static let markLetterWeights: [UInt32: UInt32] = {
        var out: [UInt32: UInt32] = [:]
        for index in stride(from: 0, to: markLetters.count - 1, by: 2) { out[markLetters[index]] = markLetters[index + 1] }
        return out
    }()

    /// `numbers`, each by its scalar: its value, and its weight at the third level.
    static let numberValues: [UInt32: Number] = {
        var out: [UInt32: Number] = [:]
        for index in stride(from: 0, to: numbers.count - 2, by: 3) {
            out[numbers[index]] = Number(value: numbers[index + 1], tertiary: numbers[index + 2])
        }
        return out
    }()

    /// `contractions` by their two scalars, the first shifted 32.
    static let contracted: [UInt64: UInt32] = {
        var out: [UInt64: UInt32] = [:]
        for index in stride(from: 0, to: contractions.count - 2, by: 3) {
            out[(UInt64(contractions[index]) << 32) | UInt64(contractions[index + 1])] = contractions[index + 2]
        }
        return out
    }()

    /// `variants` weighed: the letter of a-z at the first level, and its own mark at the second.
    static let variantWeights: [UInt32: Weight] = {
        var weights: [UInt32: Weight] = [:]
        for index in stride(from: 0, to: variants.count - 2, by: 3) {
            weights[variants[index]] = Weight(primary: latinBand + (variants[index + 1] << 8),
                                              secondary: base + variants[index + 2])
        }
        return weights
    }()

    /// The small kana, each as its letter.
    static let smallKana: [UInt32: UInt32] = [
        0x3041: 0x3042, 0x3043: 0x3044, 0x3045: 0x3046, 0x3047: 0x3048, 0x3049: 0x304A, 0x3063: 0x3064, 0x3083: 0x3084,
        0x3085: 0x3086, 0x3087: 0x3088, 0x308E: 0x308F, 0x3095: 0x304B, 0x3096: 0x3051,
    ]

    /// `localeCompare`'s sign: -1, 0 or 1.
    public static func compare(_ a: String, _ b: String) -> Int {
        if a == b && Array(a.utf16) == Array(b.utf16) { return 0 }
        let x = elements(a), y = elements(b)
        for level in 0..<3 {
            let one = weights(x, level), other = weights(y, level)
            if one != other { return one.lexicographicallyPrecedes(other) ? -1 : 1 }
        }
        return 0
    }

    static func weights(_ elements: [Element], _ level: Int) -> [UInt32] {
        elements.compactMap { (element: Element) -> UInt32? in
            let weight = level == 0 ? element.primary : level == 1 ? element.secondary : element.tertiary
            return weight == 0 ? nil : weight
        }
    }

    static func elements(_ text: String) -> [Element] {
        var out: [Element] = []
        var previous: UInt32 = 0
        //? ICU weighs "l·" as an l with a mark (Catalan's "col·lecció" beside "colla"), and so ŀ, which decomposes to it
        func middleDot(_ value: UInt32, _ tertiary: UInt32?) -> Element? {
            guard value == 0x00B7, previous == 0x6C || previous == 0x4C else { return nil }
            return Element(primary: 0, secondary: base + middleDotAfterL, tertiary: tertiary ?? lower)
        }
        let scalars = Array(text.decomposedStringWithCanonicalMapping.unicodeScalars)
        var index = 0
        while index < scalars.count {
            let scalar = scalars[index]
            index += 1
            if index < scalars.count, let letter = contracted[(UInt64(scalar.value) << 32) | UInt64(scalars[index].value)],
               let one = Unicode.Scalar(letter) {
                out.append(contentsOf: elements(of: one, tertiary: nil))
                previous = letter
                index += 1
                continue
            }
            if let dot = middleDot(scalar.value, nil) {
                out.append(dot)
                previous = scalar.value
                continue
            }
            if let weight = variableWeights[scalar.value] {
                out.append(Element(primary: weight.primary, secondary: weight.secondary, tertiary: lower))
                previous = scalar.value
                continue
            }
            let compat = Array(String(scalar).decomposedStringWithCompatibilityMapping.unicodeScalars)
            if compat == [scalar] {
                out.append(contentsOf: elements(of: scalar, tertiary: nil))
                previous = scalar.value
                continue
            }
            let category = scalar.properties.generalCategory
            for part in compat {
                let tertiary = compatTertiary(category, part)
                if let dot = middleDot(part.value, tertiary) {
                    out.append(dot)
                } else {
                    out.append(contentsOf: elements(of: part, tertiary: tertiary))
                }
                previous = part.value
            }
        }
        return out
    }

    /// The third level a compatibility form's part takes, by what the form is: a letter's case, a superscript's, an
    /// ordinal's or a halfwidth kana's own, and a symbol's part by its own case ("TM" < "™").
    static func compatTertiary(_ category: Unicode.GeneralCategory, _ part: Unicode.Scalar) -> UInt32 {
        switch category {
        case .lowercaseLetter: return compatLower
        case .uppercaseLetter, .titlecaseLetter: return compatUpper
        case .otherLetter, .modifierLetter, .otherNumber, .letterNumber: return special
        default: return part.properties.isUppercase ? compatUpper : compatLower
        }
    }

    /// One decomposed scalar's elements; `given`: the third level a compatibility form takes, nil for its own.
    static func elements(of scalar: Unicode.Scalar, tertiary given: UInt32?) -> [Element] {
        let value = scalar.value
        if let weight = variableWeights[value] {
            return [Element(primary: weight.primary, secondary: weight.secondary, tertiary: given ?? lower)]
        }
        if let weight = markWeights[value] { return [Element(primary: 0, secondary: weight, tertiary: lower)] }
        if ignorableMarks.contains(value) { return [] }
        if let letter = markLetterWeights[value] {
            return [Element(primary: latinBand + (letter << 8), secondary: base, tertiary: given ?? compatLower)]
        }
        if let number = numberValues[value] {
            return String(number.value).unicodeScalars.map { (digit: Unicode.Scalar) -> Element in
                Element(primary: digitBand + (digit.value - 0x30) * 16, secondary: base, tertiary: given ?? number.tertiary)
            }
        }
        let properties = scalar.properties
        func unlisted(_ band: UInt32) -> [Element] {
            [Element(primary: band + Self.unlisted + value, secondary: base, tertiary: given ?? lower)]
        }
        switch properties.generalCategory {
        case .nonspacingMark, .spacingMark, .enclosingMark:
            return [Element(primary: 0, secondary: base + unlistedMark + (value & 0xFFF), tertiary: lower)]
        case .control, .format, .unassigned, .surrogate, .privateUse:
            return []
        case .spaceSeparator, .lineSeparator, .paragraphSeparator:
            return [Element(primary: space, secondary: base, tertiary: given ?? compatLower)]
        case .decimalNumber:
            let digit = UInt32(max(0, properties.numericValue.map { Int($0) } ?? 0))
            return [Element(primary: digitBand + digit * 16, secondary: base, tertiary: given ?? lower)]
        case .uppercaseLetter, .lowercaseLetter, .titlecaseLetter, .modifierLetter, .otherLetter:
            return letter(scalar, given)
        case .connectorPunctuation, .dashPunctuation, .openPunctuation, .closePunctuation, .initialPunctuation,
             .finalPunctuation, .otherPunctuation:
            return unlisted(punctuationBand)
        case .currencySymbol:
            return unlisted(currencyBand)
        default:
            return unlisted(symbolBand)
        }
    }

    static func letter(_ scalar: Unicode.Scalar, _ given: UInt32?) -> [Element] {
        let properties = scalar.properties
        let isUpper = properties.generalCategory == .uppercaseLetter || properties.generalCategory == .titlecaseLetter
        let case_ = given ?? (isUpper ? upper : lower)
        let lowered = properties.lowercaseMapping.unicodeScalars.first ?? scalar
        let value = lowered.value
        func latin(_ letter: Character) -> UInt32 {
            latinBand + (UInt32(letter.asciiValue! - 0x61) << 8)
        }
        func plain(_ weight: Weight) -> Element { Element(primary: weight.primary, secondary: weight.secondary, tertiary: case_) }
        //? an expansion is its two letters with a mark of its own between them, after every accent (DUCET's 0110/0111):
        //? "ae" < "AE" < "æ", "SS" < "ß" < "st"
        let both = given ?? (isUpper ? expandedUpper : expanded)
        func expansion(_ first: Character, _ second: Character, _ mark: UInt32) -> [Element] {
            [Element(primary: latin(first), secondary: base, tertiary: both),
             Element(primary: 0, secondary: base + expansionMark + mark, tertiary: both),
             Element(primary: latin(second), secondary: base, tertiary: both)]
        }
        switch value {
        case 0x00E6: return expansion("a", "e", 0)
        case 0x0153: return expansion("o", "e", 0)
        case 0x00DF: return expansion("s", "s", 1)
        case 0x61...0x7A: return [plain(Weight(primary: latinBand + ((value - 0x61) << 8), secondary: base))]
        //? Greek's final sigma is its sigma a level down: "σ" < "Σ" < "ς" < "σa"
        case 0x03C2:
            return [Element(primary: scriptWeights[0x03C3]?.primary ?? scriptBand, secondary: base, tertiary: given ?? special)]
        default: break
        }
        if let weight = letterWeights[value] { return [plain(weight)] }
        if let weight = variantWeights[value] {
            return [plain(Weight(primary: weight.primary, secondary: base)),
                    Element(primary: 0, secondary: weight.secondary, tertiary: lower)]
        }
        if let weight = scriptWeights[value] { return [plain(weight)] }
        if let kana = kana(value, given) { return [kana] }
        return [plain(Weight(primary: script(lowered), secondary: base))]
    }

    /// A kana's element: hiragana and katakana alike at the first level, a small kana as its letter; at the third, small
    /// hiragana, hiragana, small katakana, then katakana ("ぁ" < "あ" < "ァ" < "ア").
    static func kana(_ value: UInt32, _ given: UInt32?) -> Element? {
        let isKatakana = (0x30A1...0x30F6).contains(value)
        guard isKatakana || (0x3041...0x3096).contains(value) else { return nil }
        let letter = isKatakana ? value - 0x60 : value
        let small = smallKana[letter]
        let tertiary: UInt32 = small == nil ? (isKatakana ? katakana : hiragana) : (isKatakana ? smallKatakana : smallHiragana)
        return Element(primary: kanaBand + (small ?? letter), secondary: base, tertiary: given ?? tertiary)
    }

    /// The first level of a letter in a script `scriptLetters` doesn't list: after them by code point, but for Hangul's
    /// jamo, Bopomofo, Yi and Han, each after every other script.
    static func script(_ scalar: Unicode.Scalar) -> UInt32 {
        let value = scalar.value
        switch value {
        case 0x1100...0x11FF, 0xA960...0xA97F, 0xD7B0...0xD7FF: return hangulBand + value
        case 0x3100...0x312F, 0x31A0...0x31BF: return bopomofoBand + value
        case 0xA000...0xA48F: return yiBand + value
        default: return scalar.properties.isUnifiedIdeograph ? hanBand + value : scriptBand + unlisted + value
        }
    }

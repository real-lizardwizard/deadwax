    /// The marks ICU ignores altogether.
    static let ignorableMarks: Set<UInt32> = [
        0x034F, 0xFE21, 0xFE23, 0xFE24, 0xFE25, 0xFE26, 0xFE28, 0xFE2A, 0xFE2B, 0xFE2C, 0xFE2D, 0xFE2F,
